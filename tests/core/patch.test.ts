import { expect, test } from 'vitest';
import { applyPatch, checkLocks, setApproved } from '../../src/core/patch';
import { validateTimeline } from '../../src/core/timeline';
import { makeTimeline } from '../helpers/timeline';

test('swap changes only the target', () => { const a = makeTimeline(4);
  const b = applyPatch(a, [{ op:'swapSource', segmentId:'s2', source:'raw/a.mp4', sourceIn:10, sourceOut:13, speed:1 }]);
  expect(checkLocks(a, b, { targets:['s2'], unlock:false })).toEqual([]);
  expect(b.segments.filter((s,i)=>i!==1)).toEqual(a.segments.filter((s,i)=>i!==1));
  expect(b.durationFrames).toBe(a.durationFrames); });
test('applyPatch is pure', () => { const a = makeTimeline(2); const copy = structuredClone(a);
  applyPatch(a, [{ op:'setGain', trackId:'m1', gain:0.5 }]); expect(a).toEqual(copy); });
test('touching a non-target is a violation', () => { const a = makeTimeline(3);
  const b = applyPatch(a, [{ op:'setCaptionText', captionId:'c3', text:'x' }]);
  expect(checkLocks(a, b, { targets:['c1'], unlock:false })).toHaveLength(1); });
test('approved item cannot change even when targeted', () => { const a = setApproved(makeTimeline(2), 's1', true);
  const b = applyPatch(a, [{ op:'setEffects', segmentId:'s1', effects:[{type:'pushIn'}] }]);
  expect(checkLocks(a, b, { targets:['s1'], unlock:false })[0]).toContain('approved'); });
test('retime without unlock is a violation', () => { const a = makeTimeline(3);
  const b = applyPatch(a, [{ op:'retime', segmentId:'s1', durationFrames:60 }]);
  expect(checkLocks(a, b, { targets:['s1'], unlock:false }).length).toBeGreaterThan(0);
  expect(checkLocks(a, b, { targets:['s1'], unlock:true })).toEqual([]);
  expect(b.audio).toEqual(a.audio); });
test('retime before an approved segment is refused even with unlock', () => { const a = setApproved(makeTimeline(3), 's3', true);
  const b = applyPatch(a, [{ op:'retime', segmentId:'s1', durationFrames:60 }]);
  expect(checkLocks(a, b, { targets:['s1'], unlock:true })[0]).toContain('un-approve'); });
test('speed outside 0.75-1.5 is a violation', () => { const a = makeTimeline(1);
  const b = applyPatch(a, [{ op:'swapSource', segmentId:'s1', source:'raw/a.mp4', sourceIn:0, sourceOut:6, speed:2 }]);
  expect(checkLocks(a, b, { targets:['s1'], unlock:false }).length).toBeGreaterThan(0); });
test('unknown id throws', () => { const a = makeTimeline(1);
  expect(() => applyPatch(a, [{ op:'setGain', trackId:'nope', gain:1 }])).toThrow('unknown id: nope');
  expect(() => applyPatch(a, [{ op:'setCrop', segmentId:'nope', crop:'contain' }])).toThrow('unknown id: nope');
  expect(() => applyPatch(a, [{ op:'setCaptionText', captionId:'nope', text:'x' }])).toThrow('unknown id: nope');
  expect(() => setApproved(a, 'nope', true)).toThrow('unknown id: nope'); });
test('setApproved works on segments and captions', () => { const b = setApproved(setApproved(makeTimeline(1), 's1', true), 'c1', true);
  expect(b.segments[0].approved).toBe(true); expect(b.captions[0].approved).toBe(true); });
test('setCaptionText clears words and sets animation line', () => { const a = makeTimeline(1);
  a.captions[0].words = [{ text:'hi', startFrame:0, endFrame:10 }]; a.captions[0].animation = 'word';
  const b = applyPatch(a, [{ op:'setCaptionText', captionId:'c1', text:'new' }]);
  expect(b.captions[0]).toMatchObject({ text:'new', words:[], animation:'line' }); });
test('retime shifts later segments and captions and updates duration', () => { const a = makeTimeline(3);
  const b = applyPatch(a, [{ op:'retime', segmentId:'s1', durationFrames:60 }]);
  expect(b.segments.map(s => s.startFrame)).toEqual([0, 60, 150]);
  expect(b.captions.map(c => [c.startFrame, c.endFrame])).toEqual([[0, 90], [60, 150], [150, 240]]);
  expect(b.durationFrames).toBe(240); });
test('retime adjusts sourceOut so the timeline stays valid (R1)', () => { const a = makeTimeline(3);
  const b = applyPatch(a, [{ op:'retime', segmentId:'s2', durationFrames:45 }]);
  expect(b.segments[1].sourceOut).toBeCloseTo(1.5);
  expect(validateTimeline(b, { 'raw/a.mp4': { durationSec: 60 } }).ok).toBe(true); });
test('audio track startFrame change is a violation even with unlock', () => { const a = makeTimeline(2);
  const b = structuredClone(a); b.audio[0].startFrame = 5;
  expect(checkLocks(a, b, { targets:['m1'], unlock:true }).length).toBeGreaterThan(0); });
test('setGain on a target track is allowed', () => { const a = makeTimeline(1);
  const b = applyPatch(a, [{ op:'setGain', trackId:'m1', gain:0.1 }]);
  expect(checkLocks(a, b, { targets:['m1'], unlock:false })).toEqual([]); });

const ov = { id:'o1', kind:'logo' as const, source:'raw/l.png', startFrame:0, endFrame:30, position:'top-left' as const };
test('overlay change is a violation, with and without unlock', () => { const a = makeTimeline(1); a.overlays = [ov];
  const b = structuredClone(a); b.overlays[0].endFrame = 40;
  expect(checkLocks(a, b, { targets:['s1'], unlock:false }).length).toBeGreaterThan(0);
  expect(checkLocks(a, b, { targets:['o1'], unlock:true }).length).toBeGreaterThan(0); });
test('overlay added or removed is a violation', () => { const a = makeTimeline(1); const b = structuredClone(a); b.overlays = [ov];
  expect(checkLocks(a, b, { targets:[], unlock:true }).length).toBeGreaterThan(0);
  expect(checkLocks(b, a, { targets:[], unlock:true }).length).toBeGreaterThan(0); });
test('style change is a violation', () => { const a = makeTimeline(1); const b = structuredClone(a); b.style.captionSize = 80;
  expect(checkLocks(a, b, { targets:['s1'], unlock:true }).length).toBeGreaterThan(0); });
test('segment removed is a violation', () => { const a = makeTimeline(2); const b = structuredClone(a); b.segments.pop();
  expect(checkLocks(a, b, { targets:['s2'], unlock:true }).length).toBeGreaterThan(0); });
test('caption added is a violation', () => { const a = makeTimeline(1); const b = structuredClone(a);
  b.captions.push({ ...b.captions[0], id:'c9' });
  expect(checkLocks(a, b, { targets:['c9'], unlock:true }).length).toBeGreaterThan(0); });
test('fps/width/height change is a violation', () => { const a = makeTimeline(1);
  for (const k of ['fps','width','height'] as const) { const b = structuredClone(a) as any; b[k] = 1;
    expect(checkLocks(a, b, { targets:[], unlock:true }).length).toBeGreaterThan(0); } });

test('with unlock, a non-target pure shift is allowed (segments, captions and words move together)', () => { const a = makeTimeline(3);
  a.captions[2].words = [{ text:'a', startFrame:180, endFrame:200 }, { text:'b', startFrame:200, endFrame:270 }];
  const b = applyPatch(a, [{ op:'retime', segmentId:'s1', durationFrames:60 }]);
  expect(b.captions[2].words.map(w => [w.startFrame, w.endFrame])).toEqual([[150, 170], [170, 240]]);
  expect(checkLocks(a, b, { targets:['s1'], unlock:true })).toEqual([]); });
test('with unlock, a non-target caption stretch is refused', () => { const a = makeTimeline(3);
  const b = applyPatch(a, [{ op:'retime', segmentId:'s1', durationFrames:60 }]);
  b.captions[2].endFrame = 245; // shifted start by -30 but end by -25
  expect(checkLocks(a, b, { targets:['s1'], unlock:true })).toEqual(['c3 changed but is not a target']); });
test('with unlock, a non-target caption word moved by a different delta is refused', () => { const a = makeTimeline(3);
  a.captions[2].words = [{ text:'a', startFrame:180, endFrame:200 }];
  const b = applyPatch(a, [{ op:'retime', segmentId:'s1', durationFrames:60 }]);
  b.captions[2].words[0].startFrame = 155;
  expect(checkLocks(a, b, { targets:['s1'], unlock:true })).toEqual(['c3 changed but is not a target']); });
test('with unlock, a non-target segment that changes duration is refused', () => { const a = makeTimeline(3);
  const b = structuredClone(a); b.segments[2].durationFrames = 60; b.segments[2].sourceOut = 2; b.durationFrames = 240;
  expect(checkLocks(a, b, { targets:['s1'], unlock:true })).toContain('s3 changed but is not a target'); });
test('retime rejects a non-integer or < 1 duration', () => { const a = makeTimeline(2);
  for (const d of [0, -30, 45.5, NaN]) expect(() => applyPatch(a, [{ op:'retime', segmentId:'s1', durationFrames:d }])).toThrow('invalid duration'); });
