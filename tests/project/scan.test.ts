import { afterEach, expect, test } from 'vitest';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { scanProject } from '../../src/project/scan';
import { probeMedia } from '../../src/project/probe';
import { makeProject } from '../fixtures/make';

const dirs: string[] = [];
async function track(p: Promise<string>) { const d = await p; dirs.push(d); return d; }
const tmp = () => track(fs.mkdtemp(path.join(os.tmpdir(), 'vea-scan-')));
afterEach(async () => { await Promise.all(dirs.splice(0).map(d => fs.rm(d, { recursive: true, force: true }))); });

test('scans raw and references', async () => { const d = await track(makeProject({ narration: true }));
  const s = await scanProject(d); expect(s.raw).toHaveLength(2); expect(s.references.media[0].kind).toBe('audio');
  expect(s.raw[0]).toMatchObject({ path: 'raw/a.mp4', kind: 'video', width: 1280, height: 720, fps: 30, hasAudio: true });
  expect(s.raw[0].durationSec).toBeCloseTo(5, 0); expect(s.guidelinePath).toBeNull(); });
test('Vietnamese names with spaces work', async () => { const d = await track(makeProject({ rawNames: ['cảnh 1.mp4', 'phòng khách.mp4'] }));
  expect((await scanProject(d)).raw.map(r => r.path)).toEqual(['raw/cảnh 1.mp4', 'raw/phòng khách.mp4']); });
test('decomposed (NFD) names are normalised to NFC', async () => { const d = await track(makeProject({ rawNames: ['cảnh.mp4'.normalize('NFD')] }));
  expect((await scanProject(d)).raw.map(r => r.path)).toEqual(['raw/cảnh.mp4'.normalize('NFC')]); });
test('rotation metadata swaps width and height', async () => { const d = await track(makeProject({ rotated: true }));
  const m = (await scanProject(d)).raw[0]; expect(m.height!).toBeGreaterThan(m.width!); });
test('missing raw folder', async () => { const emptyDir = await tmp();
  await expect(scanProject(emptyDir)).rejects.toMatchObject({ code: 'NO_RAW_FOLDER' }); });
test('empty raw folder', async () => { const dirWithEmptyRaw = await tmp(); await fs.mkdir(path.join(dirWithEmptyRaw, 'raw'));
  await expect(scanProject(dirWithEmptyRaw)).rejects.toMatchObject({ code: 'NO_RAW_FOOTAGE' }); });
test('not a folder', async () => { const d = await tmp(); const f = path.join(d, 'x.txt'); await fs.writeFile(f, 'hi');
  await expect(scanProject(f)).rejects.toMatchObject({ code: 'NOT_A_FOLDER' });
  await expect(scanProject(path.join(d, 'nope'))).rejects.toMatchObject({ code: 'NOT_A_FOLDER' }); });
test('no reference folder is fine', async () => { const rawOnly = await track(makeProject());
  expect((await scanProject(rawOnly)).references.media).toEqual([]); });
test('unreadable file becomes a warning', async () => { const d = await track(makeProject());
  await fs.writeFile(path.join(d, 'raw', 'bad.mp4'), 'garbage');
  const s = await scanProject(d); expect(s.warnings[0]).toContain('bad.mp4'); expect(s.raw).toHaveLength(2); });
test('reads guideline, scripts, links; ignores .vea and other files', async () => { const d = await track(makeProject({ music: true }));
  await fs.writeFile(path.join(d, 'guideline.md'), '# g');
  const ref = path.join(d, 'reference');
  await fs.writeFile(path.join(ref, 'script.txt'), 'Xin chào');
  await fs.writeFile(path.join(ref, 'sub.srt'), '1\n');
  await fs.writeFile(path.join(ref, 'links.txt'), '# c\nhttps://a.example/v\n\nnotalink\nhttp://b.example\n');
  await fs.writeFile(path.join(ref, 'pic.png'), 'x');
  await fs.mkdir(path.join(d, '.vea')); await fs.writeFile(path.join(d, '.vea', 'x.mp4'), 'x');
  const s = await scanProject(d);
  expect(s.guidelinePath).toBe('guideline.md');
  expect(s.references.scripts).toEqual([{ path: 'reference/script.txt', text: 'Xin chào' }, { path: 'reference/sub.srt', text: '1\n' }]);
  expect(s.references.links).toEqual(['https://a.example/v', 'http://b.example']);
  expect(s.references.media.map(m => m.path)).toEqual(['reference/track.mp3']);
  expect(s.warnings).toEqual([]); });
test('probeMedia reports audio-less video', async () => { const d = await track(makeProject());
  const out = path.join(d, 'raw', 'mute.mp4');
  const { execa } = await import('execa');
  await execa('ffmpeg', ['-y', '-v', 'error', '-i', path.join(d, 'raw', 'a.mp4'), '-an', '-c:v', 'copy', out]);
  expect((await probeMedia(d, 'raw/mute.mp4')).hasAudio).toBe(false); });
